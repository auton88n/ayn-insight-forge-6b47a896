/**
 * v3.13.0 — the employer's sent assessments list, with results.
 *
 * Everything shown here comes from assessment_results, a table no client
 * role can select from: the edge function reads it with the service role
 * and only ever returns it on the employer lane.
 *
 * v3.251.0 -- was still a plain shadcn <Card> on the site's global default
 * tokens, never even resume-hub-theme's own ember, let alone the real
 * .lp-panel card the rest of the redesigned dashboard now uses. Converted
 * to match, same as IntakeWizard.tsx and the Proposals list.
 */
import { useEffect, useState } from "react";
import { Badge } from "@/components/ui/badge";
import { Loader2, ShieldAlert, Timer } from "lucide-react";
import { assessmentApi, ASSESSMENT_LIMIT_NOTE, type EmployerAssessment } from "@/lib/assessments";

const STATUS_LABEL: Record<string, string> = {
  sent: "Waiting for them to start",
  started: "In progress",
  submitted: "Submitted",
  expired: "Expired",
};

const VERDICT_LABEL: Record<string, string> = {
  consistent: "Consistent with their profile",
  "partly consistent": "Partly consistent with their profile",
  inconsistent: "Inconsistent with their profile",
};

// v3.154.0 — a separate signal from the content verdict above: does the
// answer prose itself read like it was generated by an AI. Advisory only,
// shown next to the verdict, never folded into it, and only surfaced at
// all when the grader actually flagged something (a plain "human" read
// gets no badge, so this never reads as false reassurance either).
const WRITING_SIGNAL_LABEL: Record<string, string> = {
  ai_assisted: "Reads AI-assisted",
  unclear: "Writing pattern unclear",
};

// Matching resume-hub.css's own --rh-gold literally, since .lp has no
// equivalent "caution/advisory" accent of its own -- this one signal is
// deliberately not ember, the same reasoning that token was given a
// distinct hue in the first place.
const GOLD = "#b8862f";

export default function AssessmentsPanel({ reloadKey }: { reloadKey: number }) {
  const [rows, setRows] = useState<EmployerAssessment[]>([]);
  const [loading, setLoading] = useState(true);
  const [openId, setOpenId] = useState<string | null>(null);

  useEffect(() => {
    setLoading(true);
    assessmentApi.employerList()
      .then(r => setRows(r.assessments || []))
      .catch(() => setRows([]))
      .finally(() => setLoading(false));
  }, [reloadKey]);

  return (
    <div className="lp-panel space-y-3">
      <div>
        <h2 className="lp-display" style={{ fontSize: 15, color: "hsl(var(--lp-fg))" }}>Assessments you sent</h2>
        <p className="flex items-start gap-1.5 text-xs text-muted-foreground mt-1">
          <ShieldAlert className="w-3.5 h-3.5 mt-px shrink-0" />
          {ASSESSMENT_LIMIT_NOTE}
        </p>
      </div>

      {loading && <Loader2 className="w-4 h-4 animate-spin text-muted-foreground" />}
      {!loading && rows.length === 0 && (
        <p className="text-sm text-muted-foreground">
          Nothing sent yet. Open a candidate and send them an assessment before you decide on a proposal.
        </p>
      )}

      {rows.map(a => {
        const isOpen = openId === a.id;
        return (
          <div key={a.id} className="rounded-lg px-3 py-2.5 space-y-2" style={{ border: "1px solid hsl(var(--lp-border-soft))" }}>
            <div className="flex items-center justify-between gap-3">
              <div className="min-w-0">
                <p className="text-sm font-medium truncate">
                  {a.first_name || a.job_title || "Candidate"}
                </p>
                <p className="text-[11px] text-muted-foreground flex items-center gap-1 truncate">
                  <Timer className="w-3 h-3 shrink-0" />
                  {a.first_name && a.job_title ? `${a.job_title} · ` : ""}
                  {a.question_count} questions · {Math.round(a.time_limit_seconds / 60)} minute limit
                </p>
              </div>
              <Badge variant={a.status === "submitted" ? "secondary" : "outline"}>
                {STATUS_LABEL[a.status] || a.status}
              </Badge>
            </div>

            {a.result && (
              <>
                <div className="flex items-center gap-3 flex-wrap">
                  <span className="text-lg font-semibold">{a.result.overall_score}</span>
                  <Badge variant="secondary" className="font-normal">
                    {VERDICT_LABEL[a.result.verification_verdict] || a.result.verification_verdict}
                  </Badge>
                  {a.result.writing_signal !== "human" && (
                    <Badge
                      variant="outline"
                      className="font-normal"
                      style={{ color: GOLD, borderColor: GOLD }}
                      title={a.result.writing_signal_note || undefined}
                    >
                      {WRITING_SIGNAL_LABEL[a.result.writing_signal] || a.result.writing_signal}
                    </Badge>
                  )}
                  <button
                    type="button"
                    className="ml-auto text-xs"
                    style={{ background: "none", border: "none", padding: 0, font: "inherit", cursor: "pointer", color: "hsl(var(--lp-muted))" }}
                    onClick={() => setOpenId(isOpen ? null : a.id)}
                  >
                    {isOpen ? "Hide detail" : "Read the detail"}
                  </button>
                </div>
                {a.result.employer_summary && (
                  <p className="text-sm leading-relaxed">{a.result.employer_summary}</p>
                )}
                {a.result.writing_signal !== "human" && a.result.writing_signal_note && (
                  <p className="text-xs leading-relaxed" style={{ color: GOLD }}>{a.result.writing_signal_note}</p>
                )}

                {isOpen && (
                  <div className="space-y-3 pt-1">
                    {a.result.strengths.length > 0 && (
                      <div>
                        <p className="text-xs font-semibold uppercase tracking-wider text-muted-foreground mb-1">Strengths</p>
                        <ul className="space-y-0.5">
                          {a.result.strengths.map((s, i) => <li key={i} className="text-sm leading-relaxed">{s}</li>)}
                        </ul>
                      </div>
                    )}
                    {a.result.concerns.length > 0 && (
                      <div>
                        <p className="text-xs font-semibold uppercase tracking-wider text-muted-foreground mb-1">Concerns</p>
                        <ul className="space-y-0.5">
                          {a.result.concerns.map((s, i) => <li key={i} className="text-sm leading-relaxed">{s}</li>)}
                        </ul>
                      </div>
                    )}
                    <div className="space-y-2">
                      <p className="text-xs font-semibold uppercase tracking-wider text-muted-foreground">Per question</p>
                      {a.result.per_question.map(q => (
                        <div key={q.id} className="rounded-md px-3 py-2 space-y-1" style={{ border: "1px solid hsl(var(--lp-border-soft))" }}>
                          <div className="flex items-start justify-between gap-3">
                            <p className="text-sm leading-relaxed">
                              {q.is_follow_up && (
                                <span className="text-[10px] uppercase tracking-wider text-muted-foreground mr-1.5 align-middle">
                                  Live follow-up
                                </span>
                              )}
                              {q.question}
                            </p>
                            <Badge variant="outline" className="shrink-0 font-normal">{q.score}</Badge>
                          </div>
                          {q.answer && (
                            <p className="text-xs text-muted-foreground leading-relaxed whitespace-pre-wrap">
                              {q.answer}
                            </p>
                          )}
                          <p className="text-xs leading-relaxed">{q.observed}</p>
                          <p className="text-[11px] text-muted-foreground">
                            {q.seconds_spent} seconds on this question
                          </p>
                        </div>
                      ))}
                    </div>
                  </div>
                )}
              </>
            )}
          </div>
        );
      })}
    </div>
  );
}
